import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createApp} from '../server/app.js';
import {designFixture} from './fixtures/design.mjs';
import {readAndRenderPdf} from './helpers/pdf.mjs';
import {PDFDocument,PDFName,PDFArray} from 'pdf-lib';

const root=path.resolve(import.meta.dirname,'..'),temp=fs.mkdtempSync(path.join(os.tmpdir(),'canvas-design-browser-'));
const instance=createApp({root,dataDir:temp,demo:true,maxImages:2,agentModel:'test',imageModel:'test',sandboxMode:'off'});
const session=instance.store.create(),fixture=await designFixture();
const logo=instance.store.addImage(session,fixture.assets.get(fixture.logoId),{label:'品牌 Logo.png',kind:'upload',demo:false,width:480,height:480});
const photo=instance.store.addImage(session,fixture.assets.get(fixture.photoId),{label:'产品图.png',kind:'upload',demo:false,width:1200,height:500});
const server=await new Promise((resolve,reject)=>{const s=instance.app.listen(0,'127.0.0.1');s.once('listening',()=>resolve(s));s.once('error',reject);});
const base=`http://127.0.0.1:${server.address().port}`;let browser;
try{
  browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);await page.waitForFunction(()=>!document.getElementById('designButton').disabled);
  assert.equal(await page.locator('.top-actions #designButton').innerText(),'编辑设计稿');
  assert.equal(await page.locator('#exportButton').innerText(),'下载作品');
  fs.mkdirSync(path.join(root,'test-results/design'),{recursive:true});
  await page.screenshot({path:path.join(root,'test-results/design/workspace-desktop.png'),fullPage:true});
  for(const colorSpace of ['rgb','cmyk']){
    await page.locator('#exportButton').click();await page.locator('#downloadFormat').selectOption('pdf');
    await page.waitForFunction(()=>!document.querySelector('#downloadColor [value="cmyk"]').disabled);
    await page.locator('#downloadColor').selectOption(colorSpace);await page.locator('#downloadUnit').selectOption('mm');
    await page.locator('#downloadWidth').fill('180');await page.locator('#downloadHeight').fill('240');
    assert.match(await page.locator('#downloadQuality').innerText(),/PPI/);
    if(colorSpace==='cmyk')await page.screenshot({path:path.join(root,'test-results/design/workspace-download.png'),fullPage:true});
    const downloading=page.waitForEvent('download');await page.locator('#downloadSubmit').click();const download=await downloading;
    const file=path.join(root,`test-results/design/workspace-${colorSpace}.pdf`);await download.saveAs(file);
    const pdf=await PDFDocument.load(fs.readFileSync(file));assert.ok(Math.abs(pdf.getPage(0).getWidth()-180*72/25.4)<.001);
    if(colorSpace==='cmyk')assert.ok(pdf.catalog.lookup(PDFName.of('OutputIntents'),PDFArray));
    await page.waitForFunction(()=>!document.getElementById('downloadDialog').open);
  }
  assert.equal(instance.documents.get(session.id),null,'workspace downloads do not create a design');
  assert.equal(session.versions.length,2);assert.deepEqual(session.referenceIds,[logo.id,photo.id]);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#exportButton').click();await page.locator('#downloadFormat').selectOption('pdf');
  await page.screenshot({path:path.join(root,'test-results/design/workspace-mobile.png'),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'workspace and download panel fit mobile');
  await page.locator('[aria-label="关闭下载面板"]').click();await page.setViewportSize({width:1440,height:1000});
  await page.locator('#designButton').click();await page.waitForURL('**/design.html?session=*');
  await page.waitForFunction(()=>document.getElementById('designStatus').textContent==='尚未创建设计稿');
  assert.equal(new URL(page.url()).searchParams.get('source'),photo.id);
  assert.match(await page.locator('#designSourceNotice').innerText(),/不能逐字修改/);
  await page.locator('#designTitle').fill('夏日品牌海报');await page.locator('#pageWidth').fill('800');await page.locator('#pageHeight').fill('1000');
  await page.locator('#createDesign').click();
  const saved=()=>page.waitForFunction(()=>document.getElementById('designStatus').textContent==='已保存'&&!document.getElementById('saveDesign').disabled&&document.getElementById('designPreview').naturalWidth>0);
  await saved();
  await page.locator('#addText').click();await page.locator('[data-property="text"]').fill('夏日营业时间\n10:00-20:00');
  await page.locator('#saveDesign').click();await saved();
  await page.locator('#assetSelect').selectOption(logo.id);await page.locator('#addImage').click();
  await page.locator('[data-property="x"]').fill('500');await page.locator('[data-property="y"]').fill('200');await page.locator('[data-property="width"]').fill('200');await page.locator('[data-property="height"]').fill('200');
  await page.locator('#saveDesign').click();await saved();
  const record=instance.documents.require(session.id),textId=record.document.pages[0].objects[1].id;
  assert.equal(record.document.pages[0].width,800);assert.equal(record.document.pages[0].unit,'px');
  assert.equal(record.document.pages[0].objects[0].assetId,photo.id,'current artwork is carried into the editor');
  assert.equal(record.document.pages[0].objects[2].assetId,logo.id);
  await page.locator('#snapshotDesign').click();await saved();
  await page.locator(`[data-object="${textId}"]`).click();await page.locator('[data-property="text"]').fill('修改后的营业时间');await page.locator('#saveDesign').click();await saved();
  assert.equal(instance.documents.require(session.id).document.pages[0].objects[2].assetId,logo.id,'local text edit preserves logo');
  await page.locator('#restoreDesign').click();await saved();
  assert.equal(instance.documents.require(session.id).document.pages[0].objects[1].text,'夏日营业时间\n10:00-20:00');
  assert.equal(session.versions.length,2,'design versions do not become legacy PNG versions');assert.deepEqual(session.referenceIds,[logo.id,photo.id]);
  await page.reload();await saved();assert.equal(await page.locator('[data-object]').count(),3);
  await page.locator('#pageUnit').selectOption('mm');await page.locator('#saveDesign').click();await saved();
  assert.ok(Math.abs(instance.documents.require(session.id).document.pages[0].width-800*25.4/96)<.001);
  await page.locator('#pageUnit').selectOption('px');await page.locator('#saveDesign').click();await saved();
  fs.mkdirSync(path.join(root,'test-results/design'),{recursive:true});
  for(const value of ['pdf-rgb','pdf-cmyk']){
    await page.locator('#designFormat').selectOption(value);
    const downloading=page.waitForEvent('download');await page.locator('#downloadDesign').click();const download=await downloading;
    const file=path.join(root,`test-results/design/browser-${value}.pdf`);await download.saveAs(file);await saved();
    const bytes=fs.readFileSync(file),pdf=await PDFDocument.load(bytes);assert.equal(pdf.getPageCount(),1);
    assert.match((await readAndRenderPdf(bytes)).text,/夏日营业时间/);
    if(value==='pdf-cmyk')assert.ok(pdf.catalog.lookup(PDFName.of('OutputIntents'),PDFArray));
  }
  await page.screenshot({path:path.join(root,'test-results/design/editor-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(root,'test-results/design/editor-mobile.png'),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile page does not overflow horizontally');
  await page.locator(`[data-object="${textId}"]`).click();await page.locator('[data-property="height"]').fill('1');await page.locator('#saveDesign').click();await saved();
  assert.match(await page.locator('#designIssues').innerText(),/超出文本框/);
  await page.locator('#downloadDesign').click();await page.waitForFunction(()=>document.getElementById('designMessage').textContent.includes('超出文本框'));
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS: workspace entry, current-image RGB/CMYK downloads, source import, edit/save/restore, custom units, independent assets, overflow prevention, desktop and mobile.');
}finally{await browser?.close();instance.shutdown();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));fs.rmSync(temp,{recursive:true,force:true});}
